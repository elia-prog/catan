package model; // הגדרת החבילה שבה נמצא הקובץ - מודל המשחק

/**
 * אינאם המייצג את סוגי המשאבים השונים במשחק קטאן
 */
public enum ResourceType {
    WOOD,   // משאב עץ - משמש לבניית דרכים ויישובים
    BRICK,  // משאב לבנה - משמש לבניית דרכים ויישובים
    SHEEP,  // משאב צמר (כבשה) - משמש לבניית יישובים וקניית קלפי פיתוח
    WHEAT,  // משאב חיטה - משמש לבניית יישובים, ערים וקניית קלפי פיתוח
    ORE,    // משאב עפרה (ברזל) - משמש לבניית ערים וקניית קלפי פיתוח
    NONE;    // מייצג חוסר משאב, למשל במקרה של משבצת מדבר

    /**
     * פונקציה המחזירה את שם המשאב בעברית.
     * [יעילות: O(1)] - זמן ריצה קבוע.
     * @return מחרוזת המייצגת את שם המשאב בעברית.
     */
    public String toHebrew() {
        switch (this) { // בדיקת סוג המשאב הנוכחי
            case WOOD: return "עץ"; // החזרת השם עבור עץ
            case BRICK: return "לבנה"; // החזרת השם עבור לבנה
            case SHEEP: return "כבשה"; // החזרת השם עבור כבשה
            case WHEAT: return "חיטה"; // החזרת השם עבור חיטה
            case ORE: return "עפרה"; // החזרת השם עבור עפרה
            default: return "ללא"; // החזרת "ללא" עבור כל מקרה אחר (כמו NONE)
        }
    }
}
