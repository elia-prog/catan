package model; // הגדרת החבילה שבה נמצא הקובץ - מודל המשחק

/**
 * אינאם המייצג את סוגי קלפי הפיתוח השונים במשחק קטאן
 */
public enum DevCardType {
    KNIGHT,          // קלף אביר: מאפשר להזיז את השודד ולגנוב משאב משחקן אחר
    VICTORY_POINT,   // קלף נקודת ניצחון: מעניק נקודה אחת נוספת לניצחון (בדרך כלל נשאר חסוי)
    ROAD_BUILDING,   // קלף בניית דרכים: מאפשר לבנות שני כבישים חדשים ללא עלות משאבים
    MONOPOLY,        // קלף מונופול: מאפשר לבחור סוג משאב ולקבל את כל היחידות שלו מכל שאר השחקנים
    YEAR_OF_PLENTY   // קלף שנת שפע: מאפשר לקחת שני משאבים לבחירה מהקופה ללא עלות
}
